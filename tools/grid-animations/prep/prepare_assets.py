#!/usr/bin/env python3
"""Cut the scene assets out of the original 3000x2351 grid stills.

The originals were replaced by 480px versions in the app, so they are read from git history (commit 4378c50).
Run from anywhere inside the repo:  python3 prep/prepare_assets.py   (needs Pillow and numpy)

Everything in assets/ except the hand-authored *.json geometry notes is regenerated by this script.
"""

import io
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent.parent
ASSETS = HERE / 'assets'
SOURCE_COMMIT = '4378c50'
ORIGINALS = {
    'catalogue': 'public/projects/espacio-ideal-catalogues/espacio-catalogues-placeholder-1.webp',
    'chair': 'public/projects/espacio-ideal-website/espacio-website-placeholder.webp',
    'years': 'public/projects/25-years/biglieri-25-years-ph.webp',
    'cube': 'public/projects/biglieri-rebrand/biglieri-bph.webp',
}
BG = np.array([0x0D, 0x0D, 0x0D])


def original(name):
    data = subprocess.run(
        ['git', 'show', f'{SOURCE_COMMIT}:{ORIGINALS[name]}'], check=True, capture_output=True, cwd=HERE
    ).stdout
    return Image.open(io.BytesIO(data)).convert('RGB')


def save(img, name):
    img.save(ASSETS / name, optimize=True)
    print(f'  {name} {img.size}')


def grain_tile():
    """A seamless tile of the print streaks, from the cube's flat white face (alpha = how dark the speck is)."""
    face = np.asarray(original('cube').crop((1460, 900, 1972, 1348))).astype(float)
    lum = face.mean(axis=2)
    alpha = np.clip((250 - lum) / (250 - 13), 0, 1)
    # Mirror into a 2x2 tile so it repeats without seams.
    tile = np.block([[alpha, alpha[:, ::-1]], [alpha[::-1, :], alpha[::-1, ::-1]]])
    rgba = np.zeros(tile.shape + (4,), np.uint8)
    rgba[..., :3] = 0x0D
    rgba[..., 3] = np.round(tile * 255)
    save(Image.fromarray(rgba, 'RGBA'), 'grain.png')


def years():
    """The blue square with its type and grain, cut exactly at its edges (measured: x 1004-1995, y 680-1670)."""
    save(original('years').crop((1004, 680, 1996, 1671)), 'years-square.png')


def _fit_circle(pts):
    """Algebraic least-squares circle through points (x, y); returns (cx, cy, r)."""
    x, y = pts[:, 0], pts[:, 1]
    A = np.c_[2 * x, 2 * y, np.ones(len(x))]
    cx, cy, c = np.linalg.lstsq(A, x**2 + y**2, rcond=None)[0]
    return cx, cy, np.sqrt(c + cx**2 + cy**2)


def _repair_letter(rgb, chair, box, centre, reach=110):
    """Rebuild the part of a letter hidden under the chair's tubes.

    The hidden stretch is a short piece of a curved stroke (the P's bowl, the C's left side), so circles are
    fitted locally to the visible outer and inner edges just beside it, and the hidden pixels are refilled from
    those circles with anti-aliased coverage.
    """
    from scipy import ndimage

    x0, y0, x1, y1 = box
    sub = rgb[y0:y1, x0:x1].astype(float)
    lum = sub.mean(axis=2)
    hidden = ndimage.binary_dilation(chair[y0:y1, x0:x1], iterations=7)
    letter = (lum > 128) & ~hidden
    edge = letter & ~ndimage.binary_erosion(letter) & ~ndimage.binary_dilation(hidden, iterations=2)
    ey, ex = np.nonzero(edge)
    near = ndimage.distance_transform_edt(~hidden)[ey, ex] < reach
    pts = np.c_[ex[near] + x0, ey[near] + y0].astype(float)
    rad = np.hypot(pts[:, 0] - centre[0], pts[:, 1] - centre[1])
    split = np.median(rad)
    outer = _fit_circle(pts[rad >= split])
    inner = _fit_circle(pts[rad < split])

    hy, hx = np.nonzero(hidden)
    gx, gy = hx + x0, hy + y0
    d_out = np.hypot(gx - outer[0], gy - outer[1])
    d_in = np.hypot(gx - inner[0], gy - inner[1])
    cover = np.clip(0.5 + outer[2] - d_out, 0, 1) * np.clip(0.5 + d_in - inner[2], 0, 1)
    fill = BG + (255 - BG) * cover[:, None]
    out = rgb.copy()
    out[gy, gx] = np.round(fill).astype(np.uint8)
    # Trim burrs where the rebuilt stroke meets the original: bright pixels just beside the hidden stretch that
    # lie clearly outside the fitted stroke were tube highlights, not letter.
    band = ndimage.binary_dilation(hidden, iterations=12) & ~hidden
    by, bx = np.nonzero(band)
    bxa, bya = bx + x0, by + y0
    outside = (np.hypot(bxa - outer[0], bya - outer[1]) > outer[2] + 1.5) | (
        np.hypot(bxa - inner[0], bya - inner[1]) < inner[2] - 1.5
    )
    trim = outside & (lum[by, bx] > 60)
    out[bya[trim], bxa[trim]] = BG.astype(np.uint8)
    print(f'    repaired {hidden.sum()} px: outer r={outer[2]:.1f} inner r={inner[2]:.1f}')
    return out


def _chair_mask(rgb):
    """Pixels belonging to the chair: its saturated olive body plus the highlights and specks within its tubes."""
    from scipy import ndimage

    a = rgb.astype(int)
    sat = (a[..., 0] - a[..., 2]) > 50
    lab, n = ndimage.label(ndimage.binary_dilation(sat, iterations=6))
    sizes = ndimage.sum(sat, lab, range(1, n + 1))
    body = (lab == np.argmax(sizes) + 1) & sat
    # Close small gaps (dark specks, pale highlights) inside tubes and straps, but not the open spaces between them.
    return ndimage.binary_closing(ndimage.binary_dilation(body, iterations=2), iterations=3)


def chair():
    """ESP and CIO with the strokes behind the chair rebuilt, and the original Wassily cut out with alpha."""
    rgb = np.asarray(original('chair'))
    mask = _chair_mask(rgb)
    fixed = _repair_letter(rgb, mask, (944, 995, 1150, 1210), centre=(1040, 1100))  # P bowl
    fixed = _repair_letter(fixed, mask, (1915, 995, 2100, 1325), centre=(2048, 1160))  # C left side
    # Anything of the chair still inside the letter crops (e.g. the tube below the P's bowl) becomes background.
    from scipy import ndimage

    leftover = ndimage.binary_dilation(mask, iterations=7)
    leftover[995:1210, 944:1150] = False
    leftover[995:1325, 1915:2100] = False
    fixed[leftover] = BG.astype(np.uint8)
    save(Image.fromarray(fixed[995:1325, 405:1150]), 'chair-esp.png')
    save(Image.fromarray(fixed[995:1325, 1915:2610]), 'chair-cio.png')
    box = (1100, 785, 1940, 1565)
    rgba = np.dstack([rgb, (mask * 255).astype(np.uint8)])[box[1] : box[3], box[0] : box[2]]
    save(Image.fromarray(rgba, 'RGBA'), 'chair-wassily.png')


def catalogue():
    """The three page spreads, and the Inmueble cover cut out of the original and flattened."""
    spreads = Image.open(HERE.parent.parent / 'public/projects/espacio-ideal-catalogues/espacio-catalogues-2.webp')
    spreads = spreads.convert('RGB')
    # Spread grid, column 2: row 2 is the drawing spread shown in the original; rows 1 and 3 follow it.
    for i, top in enumerate([991, 135, 1846]):
        save(spreads.crop((1137, top, 1998, top + 600)), f'catalogue-spread-{i}.png')

    # The cover's corners (TL, TR, BR, BL), read off the original at 6x zoom; the cover's dark edge is too close to
    # the background for reliable automatic edge detection. Left and right edges come out parallel, as a check.
    corners = [[1673.5, 816.5], [2426.5, 641.5], [2667.0, 1621.0], [1919.0, 1803.0]]

    # Flatten: map the quad onto a rectangle (perspective transform), sized like the cover's edges.
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = corners
    w = int(round((np.hypot(x1 - x0, y1 - y0) + np.hypot(x2 - x3, y2 - y3)) / 2))
    h = int(round((np.hypot(x3 - x0, y3 - y0) + np.hypot(x2 - x1, y2 - y1)) / 2))
    src = np.array(corners, float)
    dst = np.array([[0, 0], [w, 0], [w, h], [0, h]], float)
    A = []
    for (u, v), (x, y) in zip(dst, src):
        A.append([u, v, 1, 0, 0, 0, -u * x, -v * x, -x])
        A.append([0, 0, 0, u, v, 1, -u * y, -v * y, -y])
    coeffs = np.linalg.svd(np.array(A))[2][-1]
    coeffs = (coeffs / coeffs[-1])[:8]
    flat = original('catalogue').transform((w, h), Image.PERSPECTIVE, tuple(coeffs), Image.BICUBIC)
    save(flat, 'catalogue-cover.png')
    (ASSETS / 'catalogue-cover.json').write_text(json.dumps({'corners': corners, 'size': [w, h]}, indent=1) + '\n')


def main():
    ASSETS.mkdir(exist_ok=True)
    targets = sys.argv[1:] or ['grain', 'years', 'chair', 'catalogue']
    for t in targets:
        print(t)
        {'grain': grain_tile, 'years': years, 'chair': chair, 'catalogue': catalogue}[t]()


if __name__ == '__main__':
    main()
